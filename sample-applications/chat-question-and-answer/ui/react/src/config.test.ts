import { describe, expect, test } from "vitest";
import { parseSystemInfo } from "./config";

describe("parseSystemInfo", () => {
  test("parses hardware and OS details from APP_SYSTEM_INFO JSON", () => {
    expect(
      parseSystemInfo(
        '{"CPU":"AMD Ryzen 7","GPU":"Intel Arc A770","RAM":"16GB","OS":"Fedora 44"}'
      )
    ).toEqual({
      cpu: "AMD Ryzen 7",
      gpu: "Intel Arc A770",
      ram: "16GB",
      os: "Fedora 44",
    });
  });

  test("parses system details generated by the launcher", () => {
    expect(
      parseSystemInfo("CPU: AMD Ryzen 7 | GPU: Intel Arc A770 | RAM: 16 GiB | OS: Fedora 44")
    ).toEqual({
      cpu: "AMD Ryzen 7",
      gpu: "Intel Arc A770",
      ram: "16 GiB",
      os: "Fedora 44",
    });
  });
});
